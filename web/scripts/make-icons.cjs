// Writes web/components/mdi-paths.ts: the exact shapes of the icon font the app
// uses (MaterialCommunityIcons, Apache-2.0), only for the names listed here.
// Run from the repo root: node web/scripts/make-icons.cjs
const fs = require('fs');
const base = 'mobile/node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons/';
const map = require(require('path').resolve(base + 'glyphmaps/MaterialCommunityIcons.json'));
const buf = fs.readFileSync(base + 'Fonts/MaterialCommunityIcons.ttf');

const NAMES = `account-group alert arrow-up bell bell-off bone book-open-variant cake-variant calendar camera card-account-details-star
chat check chevron-down chevron-left chevron-right chevron-up clipboard-check clock close compass content-copy creation
dog email export-variant fire flashlight heart help-circle hospital-box image image-multiple lock map map-marker map-marker-path
medal message-text note-edit note-text palette paw pencil phone-alert gesture-tap puzzle star star-outline tennis-ball
trophy tree microphone sticker-emoji content-cut home school`.split(/\s+/).filter(Boolean);

const u16 = (o) => buf.readUInt16BE(o), i16 = (o) => buf.readInt16BE(o), u32 = (o) => buf.readUInt32BE(o);
const tables = {};
for (let i = 0; i < u16(4); i++) { const o = 12 + i * 16; tables[buf.toString('latin1', o, o + 4)] = u32(o + 8); }
const upm = u16(tables.head + 18), longLoca = i16(tables.head + 50), ascent = i16(tables.hhea + 4);

function glyphId(cp) {
  const c = tables.cmap;
  for (let i = 0; i < u16(c + 2); i++) {
    const s = c + u32(c + 8 + i * 8), fmt = u16(s);
    if (fmt === 12) {
      for (let g = 0; g < u32(s + 12); g++) {
        const r = s + 16 + g * 12;
        if (cp >= u32(r) && cp <= u32(r + 4)) return u32(r + 8) + cp - u32(r);
      }
    }
  }
  throw new Error('no glyph for ' + cp);
}

function path(id) {
  const loca = (n) => (longLoca ? u32(tables.loca + n * 4) : u16(tables.loca + n * 2) * 2);
  let o = tables.glyf + loca(id);
  const contours = i16(o);
  if (contours < 0) throw new Error('compound glyph ' + id);
  o += 10;
  const ends = [];
  for (let i = 0; i < contours; i++, o += 2) ends.push(u16(o));
  const n = ends[ends.length - 1] + 1;
  o += 2 + u16(o);
  const flags = [];
  while (flags.length < n) {
    const f = buf[o++]; flags.push(f);
    if (f & 8) for (let r = buf[o++]; r > 0; r--) flags.push(f);
  }
  const axis = (shortBit, sameBit) => {
    let v = 0;
    return flags.map((f) => {
      if (f & shortBit) { const d = buf[o++]; v += f & sameBit ? d : -d; }
      else if (!(f & sameBit)) { v += i16(o); o += 2; }
      return v;
    });
  };
  const xs = axis(2, 16), ys = axis(4, 32);
  const k = 24 / upm, f = (v) => +v.toFixed(2);
  const P = (p) => `${f(p.x * k)} ${f((ascent - p.y) * k)}`;
  const mid = (a, b) => ({ x: (a.x + b.x) / 2, y: (a.y + b.y) / 2, on: true });
  let d = '', start = 0;
  for (const end of ends) {
    let pts = [];
    for (let i = start; i <= end; i++) pts.push({ x: xs[i], y: ys[i], on: !!(flags[i] & 1) });
    start = end + 1;
    const first = pts.findIndex((p) => p.on);
    pts = first < 0 ? [mid(pts[0], pts[pts.length - 1]), ...pts] : [...pts.slice(first), ...pts.slice(0, first)];
    d += 'M' + P(pts[0]);
    for (let i = 1; i < pts.length; i++) {
      const p = pts[i];
      if (p.on) { d += 'L' + P(p); continue; }
      const next = pts[(i + 1) % pts.length];
      const to = next.on ? next : mid(p, next);
      d += `Q${P(p)} ${P(to)}`;
      if (next.on) i++;
    }
    d += 'Z';
  }
  return d;
}

const lines = NAMES.map((name) => {
  if (!(name in map)) throw new Error('unknown icon ' + name);
  return `  '${name}': '${path(glyphId(map[name]))}',`;
});
fs.writeFileSync('web/components/mdi-paths.ts',
  `// Generated by web/scripts/make-icons.cjs. Do not edit by hand.\nexport const MDI = {\n${lines.join('\n')}\n} as const;\n`);
console.log('wrote', lines.length, 'icons');
